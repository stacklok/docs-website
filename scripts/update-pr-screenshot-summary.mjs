// CI-only: regenerates the visual-regression screenshot summary (see
// pr-screenshot-summary.mjs) and folds it into the pull request's
// description, inside a fenced marker block. Replaces just that block if
// one already exists (e.g. from a previous push), and appends the summary
// after the author's description.
//
// Requires GH_TOKEN (or GITHUB_TOKEN) with pull-requests: write, plus
// PR_NUMBER / BASE_SHA / HEAD_SHA in the environment — see
// .github/workflows/pr-screenshot-summary.yaml, the only intended caller.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const FENCE_START = '<!-- pr-screenshot-summary:start -->';
const FENCE_END = '<!-- pr-screenshot-summary:end -->';
const FENCE_HEADING = '## Visual regression screenshots';
const FENCE_NOTE =
  '_Auto-generated by CI from `scripts/pr-screenshot-summary.mjs` — edits inside this block are overwritten on the next push._';

function requiredEnv(name) {
  const value = process.env[name];
  if (!value) throw new Error(`${name} must be set`);
  return value;
}

function gh(args) {
  return execFileSync('gh', args, { encoding: 'utf-8' });
}

/** Appends the summary after the author's description, moving an existing
 * summary block to the end if an earlier run placed it elsewhere. */
function withFencedSection(body, fenced) {
  const description = removeFencedSection(body).trimEnd();
  return description.trim().length > 0 ? `${description}\n\n${fenced}` : fenced;
}

/** Drops an existing summary and its separator when snapshot changes disappear.
 * Supports both the old leading placement and the appended placement. */
function removeFencedSection(body) {
  const startIdx = body.indexOf(FENCE_START);
  const endIdx = body.indexOf(FENCE_END);
  if (startIdx === -1 || endIdx === -1 || endIdx <= startIdx) return body;
  const before = body.slice(0, startIdx);
  const after = body.slice(endIdx + FENCE_END.length);
  if (after.trim().length === 0) {
    return before.replace(/\n{1,2}$/, '');
  }
  return before + after.replace(/^\n+/, '');
}

function main() {
  const prNumber = requiredEnv('PR_NUMBER');
  const baseSha = requiredEnv('BASE_SHA');
  const headSha = requiredEnv('HEAD_SHA');

  const summary = execFileSync(
    'node',
    ['scripts/pr-screenshot-summary.mjs', '--base', baseSha, '--head', headSha],
    { encoding: 'utf-8' }
  ).trim();

  const currentBody = gh([
    'pr',
    'view',
    prNumber,
    '--json',
    'body',
    '-q',
    '.body',
  ]);

  let newBody;
  if (summary.startsWith('No visual-regression')) {
    newBody = removeFencedSection(currentBody);
    if (newBody === currentBody) {
      console.log('No snapshot changes — leaving PR description untouched.');
      return;
    }
    console.log(
      'No snapshot changes remain — removing the stale screenshot summary.'
    );
  } else {
    const fenced = `${FENCE_START}\n${FENCE_HEADING}\n\n${FENCE_NOTE}\n\n${summary}\n${FENCE_END}`;
    newBody = withFencedSection(currentBody, fenced);
    if (newBody === currentBody) {
      console.log('Screenshot summary unchanged — skipping PR body update.');
      return;
    }
  }

  const tmpFile = path.join(os.tmpdir(), `pr-${prNumber}-body.md`);
  fs.writeFileSync(tmpFile, newBody);
  gh(['pr', 'edit', prNumber, '--body-file', tmpFile]);
  console.log(`Updated PR #${prNumber} description with screenshot summary.`);
}

main();
